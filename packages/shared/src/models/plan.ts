import { z } from 'zod';
import { AppError } from '../errors.js';
import { DependencyGraph } from '../graph/dependencyGraph.js';

export const PLAN_STATUSES = [
  'DRAFT',
  'PENDING_APPROVAL',
  'APPROVED',
  'REJECTED',
  'EXECUTING',
  'COMPLETED',
  'FAILED',
] as const;

export const PlanStatusSchema = z.enum(PLAN_STATUSES, {
  message: `Plan status must be one of ${PLAN_STATUSES.join(', ')}`,
});

export type PlanStatus = z.infer<typeof PlanStatusSchema>;

/**
 * Schema for a single task within a generated plan.
 * Must include task identifier, scope files, and acceptance criteria.
 */
export const PlanTaskSchema = z.object({
  id: z.string().min(1, 'Task ID cannot be empty'),
  title: z.string().min(1, 'Task title cannot be empty'),
  description: z.string().nullable().optional().default(null),
  scope_files: z
    .array(z.string().min(1, 'Scope file path cannot be empty'))
    .min(1, 'Task must specify at least one file in scope'),
  acceptance_criteria: z
    .array(z.string().min(1, 'Acceptance criterion cannot be empty'))
    .min(1, 'Task must specify at least one acceptance criterion'),
  dependencies: z.array(z.string().min(1)).default([]),
  test_commands: z.array(z.string().min(1)).default([]),
  priority: z.number().int().default(0),
  timeout_minutes: z.number().int().min(1).default(30),
  worker_type: z.string().min(1).default('agy'),
});

export type PlanTask = z.infer<typeof PlanTaskSchema>;

/**
 * Flexible input schema for a task in a plan, normalizing field name variations
 * such as `scope` / `files` for `scope_files`, and `acceptance` for `acceptance_criteria`.
 */
export const PlanTaskInputSchema = z
  .object({
    id: z.string().min(1, 'Task ID cannot be empty'),
    title: z.string().min(1, 'Task title cannot be empty'),
    description: z.string().nullable().optional().default(null),
    scope_files: z.array(z.string().min(1)).optional(),
    scope: z.array(z.string().min(1)).optional(),
    files: z.array(z.string().min(1)).optional(),
    acceptance_criteria: z.array(z.string().min(1)).optional(),
    acceptance: z.array(z.string().min(1)).optional(),
    dependencies: z.array(z.string().min(1)).optional().default([]),
    test_commands: z.array(z.string().min(1)).optional().default([]),
    priority: z.number().int().optional().default(0),
    timeout_minutes: z.number().int().min(1).optional().default(30),
    worker_type: z.string().min(1).optional().default('agy'),
  })
  .transform((val): PlanTask => {
    const scope_files = val.scope_files ?? val.files ?? val.scope ?? [];
    if (scope_files.length === 0) {
      throw new Error('Task must specify at least one file in scope');
    }
    const acceptance_criteria = val.acceptance_criteria ?? val.acceptance ?? [];
    if (acceptance_criteria.length === 0) {
      throw new Error('Task must specify at least one acceptance criterion');
    }
    return {
      id: val.id,
      title: val.title,
      description: val.description ?? null,
      scope_files,
      acceptance_criteria,
      dependencies: val.dependencies ?? [],
      test_commands: val.test_commands ?? [],
      priority: val.priority ?? 0,
      timeout_minutes: val.timeout_minutes ?? 30,
      worker_type: val.worker_type ?? 'agy',
    };
  });

export type PlanTaskInput = z.input<typeof PlanTaskInputSchema>;

