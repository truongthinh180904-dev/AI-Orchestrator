/**
 * Extracts a JSON object from text that may contain markdown fences or surrounding chatter.
 */
export function extractJsonPlan(rawText: string): unknown {
  const trimmed = rawText.trim();
  if (!trimmed) {
    throw new AppError('INVALID_PLAN_SCHEMA', 'Planner output is empty', {
      rawText,
    });
  }

  // 1. Try markdown code fences ```json ... ``` or ``` ... ```
  const codeBlockRegex = /```(?:json)?\s*([\s\S]*?)\s*```/i;
  const match = codeBlockRegex.exec(trimmed);
  if (match && match[1]) {
    try {
      return JSON.parse(match[1]);
    } catch {
      // Continue to next extraction strategy
    }
  }

  // 2. Direct JSON parse
  try {
    return JSON.parse(trimmed);
  } catch {
    // Continue to substring search
  }

  // 3. Find first outer balanced '{' and '}'
  const firstBrace = trimmed.indexOf('{');
  const lastBrace = trimmed.lastIndexOf('}');
  if (firstBrace !== -1 && lastBrace > firstBrace) {
    const candidate = trimmed.substring(firstBrace, lastBrace + 1);
    try {
      return JSON.parse(candidate);
    } catch (err) {
      throw new AppError(
        'INVALID_PLAN_SCHEMA',
        `Failed to parse plan JSON: ${(err as Error).message}`,
        {
          rawSnippet: candidate.substring(0, 500),
        },
      );
    }
  }

  throw new AppError('INVALID_PLAN_SCHEMA', 'No valid JSON object found in planner output', {
    rawSnippet: trimmed.substring(0, 300),
  });
}

/**
 * Validates the dependency graph of plan tasks:
 * 1. Checks that all task IDs are unique within the plan.
 * 2. Checks that every dependency references an existing task ID in the plan.
 * 3. Checks that there are no circular dependencies.
 */
export function validatePlanTasksGraph(tasks: PlanTask[]): void {
  const seenIds = new Set<string>();
  for (const task of tasks) {
    if (seenIds.has(task.id)) {
      throw new AppError(
        'DUPLICATE_TASK_ID',
        `Plan contains duplicate task ID: '${task.id}'`,
        { taskId: task.id },
      );
    }
    seenIds.add(task.id);
  }

  for (const task of tasks) {
    for (const depId of task.dependencies) {
      if (!seenIds.has(depId)) {
        throw new AppError(
          'PLAN_MISSING_DEPENDENCY',
          `Task '${task.id}' depends on non-existent task '${depId}' in the plan`,
          {
            taskId: task.id,
            missingDependency: depId,
          },
        );
      }
      if (depId === task.id) {
        throw new AppError(
          'PLAN_DEPENDENCY_CYCLE',
          `Task '${task.id}' cannot depend on itself`,
          {
            taskId: task.id,
          },
        );
      }
    }
  }

  const graph = new DependencyGraph(
    tasks.map((t) => ({
      id: t.id,
      dependencies: t.dependencies,
      priority: t.priority,
    })),
  );

  const cycleResult = graph.detectCycle();
  if (cycleResult.hasCycle && cycleResult.cycle) {
    throw new AppError(
      'PLAN_DEPENDENCY_CYCLE',
      `Plan task dependency graph contains a cycle: ${cycleResult.cycle.join(' -> ')}`,
      {
        cycle: cycleResult.cycle,
        allCycles: cycleResult.allCycles,
      },
    );
  }
}
